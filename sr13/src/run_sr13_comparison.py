# Helper normalization
def norm(x):
    return x.lower().strip()

def match_triples_eval(gold_list, pred_list):
    tp = 0
    matched = [False] * len(gold_list)
    for p in pred_list:
        p_s, p_rel, p_o = norm(p[0]), p[1], norm(p[2])
        for i, g in enumerate(gold_list):
            if not matched[i]:
                g_s, g_rel, g_o = norm(g[0]), g[1], norm(g[2])
                if p_rel == g_rel and (p_s in g_s or g_s in p_s) and (p_o in g_o or g_o in p_o):
                    tp += 1
                    matched[i] = True
                    break
    fp = len(pred_list) - tp
    fn = len(gold_list) - tp
    p = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    r = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    f1 = (2 * p * r) / (p + r) if (p + r) > 0 else 0.0
    return tp, fp, fn, p, r, f1

