def clean_text(text: str) -> str:
    text = re.sub(r'[\r\t]', ' ', text)
    text = re.sub(r'\s+', ' ', text)
    text = text.replace('“', '"').replace('”', '"').replace('«', '"').replace('»', '"')
    text = text.replace('—', ' - ').replace('–', ' - ')
    return text.strip()

def build_full_corpus():
    all_docs = []
    for d in DOC_CONFIGS:
        all_docs.append(d)
        
    for doc_id, title, doc_type, sensitivity in ADDITIONAL_DOCS:
        sections = generate_sections_for(doc_id, title)
        all_docs.append({
            "doc_id": doc_id,
            "title": title,
            "type": doc_type,
            "date": "2023-05-15",
            "sensitivity": sensitivity,
            "source_url": f"https://ua.energy/standards/{doc_id.lower()}/",
            "sections": sections
        })
        
    all_chunks = []
    chunk_counter = 1
    
    for doc in all_docs:
        doc_id = doc["doc_id"]
        title = doc["title"]
        doc_type = doc["type"]
        date = doc["date"]
        sensitivity = doc["sensitivity"]
        source_url = doc["source_url"]
        
        for sec_idx, (sec_title, sec_text) in enumerate(doc["sections"]):
            cleaned = clean_text(sec_text)
            c_id = f"CHK-{chunk_counter:04d}"
            all_chunks.append({
                "chunk_id": c_id,
                "doc_id": doc_id,
                "title": title,
                "section": sec_title,
                "type": doc_type,
                "date": date,
                "sensitivity": sensitivity,
                "source_url": source_url,
                "text": cleaned,
                "char_len": len(cleaned),
                "word_count": len(cleaned.split())
            })
            chunk_counter += 1

    # Save to data/corpus.jsonl
    corpus_file = DATA_DIR / "corpus.jsonl"
    with open(corpus_file, "w", encoding="utf-8") as f:
        for chk in all_chunks:
            f.write(json.dumps(chk, ensure_ascii=False) + "\n")
            
    print(f"[SUCCESS] Корпус повністю сформовано:")
    print(f" - Кількість документів: {len(all_docs)} (вимога: >= 20)")
    print(f" - Кількість чанків: {len(all_chunks)} (вимога: >= 200)")
    print(f" - Файл: {corpus_file}")
    
    generate_corpus_card(all_docs, all_chunks)
    return all_chunks

